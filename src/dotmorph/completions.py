"""Shell completion scripts for bash, zsh and fish, generated from the real argparse parser.

`--to` completes every format and tool DotMorph knows (also those whose tool isn't
installed yet), `-o` completes directories, everything else falls back to file names.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from .core import registry
from .core.formats import TOOLS, sort_actions
from .linux.paths import config_home, data_home

GUI_FLAGS = {
    "--theme": "colour theme",
    "--reduce-motion": "no animations",
    "--clipboard": "use the files copied in the file manager",
    "--no-daemon": "new window even if the daemon runs",
}


def _targets() -> list[str]:
    every: set[str] = set(TOOLS)
    for backend in registry.backends():
        for actions in backend.potential_pairs().values():
            every |= actions
    return sort_actions(every)


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, tuple[str, argparse.ArgumentParser]]:
    for action in parser._actions:  # argparse has no public API for this
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            return {name: (helps.get(name, ""), sub) for name, sub in action.choices.items()}
    return {}


def _options(sub: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in sub._actions if a.option_strings and a.help != argparse.SUPPRESS]


def _values(action: argparse.Action) -> list[str] | str | None:
    """Completion values: a list of words, 'dir', 'file', or None for a free value."""
    if action.nargs == 0:
        return None
    if action.dest == "to":
        return _targets()
    if action.choices:
        return [str(c) for c in action.choices]
    if action.dest in ("out",):
        return "dir"
    return "value"


SHORT_HELP = {"to": "target format or tool", "preset": "named set of options"}


def _help(action: argparse.Action) -> str:
    return SHORT_HELP.get(action.dest) or _clean(action.help or "")


def _clean(text: str) -> str:
    text = re.sub(r"%\((\w+)\)s", r"\1", text or "").replace("%%", "%")
    return re.sub(r"[\[\]:'\"`$\\]", "", text).split(";")[0].strip()[:70]


# ---- bash -----------------------------------------------------------------------------


def bash(parser: argparse.ArgumentParser) -> str:
    subs = _subcommands(parser)
    lines = [
        "# bash completion for dotmorph (generated by `dotmorph completions bash`)",
        "_dotmorph() {",
        '    local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    local sub="${COMP_WORDS[1]}"',
        '    case "$prev" in',
        f'        --to) COMPREPLY=($(compgen -W "{" ".join(_targets())}" -- "$cur")); return;;',
        '        -o|--out) COMPREPLY=($(compgen -d -- "$cur")); return;;',
        '        --theme) COMPREPLY=($(compgen -W "dark light glass" -- "$cur")); return;;',
    ]
    for _, sub in subs.values():
        for action in _options(sub):
            values = _values(action)
            if isinstance(values, list) and action.dest != "to" and action.dest != "theme":
                opts = "|".join(action.option_strings)
                lines.append(f'        {opts}) COMPREPLY=($(compgen -W "{" ".join(values)}" '
                             '-- "$cur")); return;;')
    lines += [
        "    esac",
        "    if [[ $COMP_CWORD -eq 1 ]]; then",
        f'        COMPREPLY=($(compgen -W "{" ".join(subs)} {" ".join(GUI_FLAGS)} -h -V" '
        '-- "$cur"))',
        "        return",
        "    fi",
        '    if [[ "$cur" == -* ]]; then',
        '        case "$sub" in',
    ]
    for name, (_, sub) in subs.items():
        flags = " ".join(s for a in _options(sub) for s in a.option_strings)
        lines.append(f'            {name}) COMPREPLY=($(compgen -W "{flags}" -- "$cur"));;')
    lines += [
        f'            *) COMPREPLY=($(compgen -W "{" ".join(GUI_FLAGS)}" -- "$cur"));;',
        "        esac",
        "    fi",
        "}",
        "complete -o default -o bashdefault -F _dotmorph dotmorph",
        "",
    ]
    return "\n".join(lines)


# ---- zsh ------------------------------------------------------------------------------


def _zsh_spec(action: argparse.Action) -> str:
    help_text = _help(action)
    values = _values(action)
    if values is None:
        suffix = ""
    elif values == "dir":
        suffix = ":directory:_files -/"
    elif values == "value":
        suffix = f":{action.metavar or action.dest}:"
    else:
        suffix = f":{action.dest}:({' '.join(values)})"
    names = action.option_strings
    if len(names) == 1:
        return f"'{names[0]}[{help_text}]{suffix}'"
    group = " ".join(names)
    return f"'({group})'{{{','.join(names)}}}'[{help_text}]{suffix}'"


def zsh(parser: argparse.ArgumentParser) -> str:
    subs = _subcommands(parser)
    described = "\n".join(f"        '{n}:{_clean(h)}'" for n, (h, _) in subs.items())
    lines = [
        "#compdef dotmorph",
        "# zsh completion for dotmorph (generated by `dotmorph completions zsh`)",
        "_dotmorph() {",
        "    local -a cmds",
        "    cmds=(",
        described,
        "    )",
        "    if (( CURRENT == 2 )); then",
        "        _describe -t commands 'dotmorph command' cmds",
        "        _arguments '--theme[colour theme]:theme:(dark light glass)' "
        "'--reduce-motion[no animations]' '--clipboard[copied files]' "
        "'--no-daemon[new window]' '*:file:_files'",
        "        return",
        "    fi",
        "    local sub=$words[2]",
        "    words=(${words[2,-1]})",
        "    (( CURRENT-- ))",
        "    case $sub in",
    ]
    for name, (_, sub) in subs.items():
        specs = [_zsh_spec(a) for a in _options(sub)]
        positional = [a for a in sub._actions if not a.option_strings and a.dest != "help"]
        for action in positional:
            if action.choices:
                specs.append(f"'1:{action.dest}:({' '.join(map(str, action.choices))})'")
            elif action.nargs in ("+", "*"):
                specs.append("'*:file:_files'")
        lines.append(f"        {name})")
        lines.append("            _arguments -s \\")
        lines += [f"                {spec} \\" for spec in specs]
        lines[-1] = lines[-1].rstrip(" \\")
        lines.append("            ;;")
    lines += ["        *) _files ;;", "    esac", "}", "", '_dotmorph "$@"', ""]
    return "\n".join(lines)


# ---- fish -----------------------------------------------------------------------------


def fish(parser: argparse.ArgumentParser) -> str:
    subs = _subcommands(parser)
    names = " ".join(subs)
    out = [
        "# fish completion for dotmorph (generated by `dotmorph completions fish`)",
        "complete -c dotmorph -f",
        f"complete -c dotmorph -n 'not __fish_seen_subcommand_from {names}' -F",
    ]
    for name, (help_text, _) in subs.items():
        out.append(f"complete -c dotmorph -n 'not __fish_seen_subcommand_from {names}' "
                   f"-a {name} -d '{_clean(help_text)}'")
    for flag, help_text in GUI_FLAGS.items():
        values = " -x -a 'dark light glass'" if flag == "--theme" else ""
        out.append(f"complete -c dotmorph -n 'not __fish_seen_subcommand_from {names}' "
                   f"-l {flag[2:]}{values} -d '{help_text}'")
    for name, (_, sub) in subs.items():
        cond = f"-n '__fish_seen_subcommand_from {name}'"
        if any(not a.option_strings and a.nargs in ("+", "*") for a in sub._actions):
            out.append(f"complete -c dotmorph {cond} -F")
        for action in _options(sub):
            if "-h" in action.option_strings:
                continue
            parts = [f"complete -c dotmorph {cond}"]
            for opt in action.option_strings:
                parts.append(f"-l {opt[2:]}" if opt.startswith("--") else f"-s {opt[1:]}")
            values = _values(action)
            if isinstance(values, list):
                parts.append(f"-x -a '{' '.join(values)}'")
            elif values == "dir":
                parts.append("-x -a '(__fish_complete_directories)'")
            elif values == "value":
                parts.append("-x")
            parts.append(f"-d '{_help(action)}'")
            out.append(" ".join(parts))
        for action in sub._actions:
            if not action.option_strings and action.choices:
                out.append(f"complete -c dotmorph {cond} -x -a '{' '.join(action.choices)}'")
    return "\n".join(out) + "\n"


GENERATORS = {"bash": bash, "zsh": zsh, "fish": fish}


def generate(shell: str, parser: argparse.ArgumentParser) -> str:
    return GENERATORS[shell](parser)


def install_path(shell: str) -> Path:
    if shell == "bash":
        return data_home() / "bash-completion" / "completions" / "dotmorph"
    if shell == "fish":
        return config_home() / "fish" / "completions" / "dotmorph.fish"
    return data_home() / "zsh" / "site-functions" / "_dotmorph"


def install(shell: str, parser: argparse.ArgumentParser) -> tuple[Path, str]:
    """Write the script; returns (path, extra instructions or '')."""
    path = install_path(shell)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate(shell, parser))
    note = ""
    if shell == "zsh":
        note = ("Add this line to ~/.zshrc before `compinit` (once), then open a new shell:\n"
                f"  fpath=({path.parent} $fpath)")
    elif shell == "bash":
        note = "Open a new shell (needs the bash-completion package)."
    return path, note
