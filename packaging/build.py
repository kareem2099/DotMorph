def _copy_package(dest: Path) -> None:
    shutil.copytree(SRC / "dotmorph", dest, ignore=shutil.ignore_patterns(
        "__pycache__", "*.pyc", "*.pyo", "venv", ".venv"))


def _dir_size_kb(path: Path) -> int:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file()) // 1024 + 1


def cmd_deb(_: argparse.Namespace) -> Path:
    ver = version()
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "root"
        _copy_package(root / "usr/lib/python3/dist-packages/dotmorph")
        launcher = root / "usr/bin/dotmorph"
        launcher.parent.mkdir(parents=True)
        launcher.write_text("#!/usr/bin/python3\nimport sys\n\nfrom dotmorph.app import main\n\n"
                            "sys.exit(main())\n")
        launcher.chmod(0o755)
        install_share(root, zsh_dir="share/zsh/vendor-completions")
        doc = root / "usr/share/doc/dotmorph"
        doc.mkdir(parents=True)
        for name in ("README.md", "CHANGELOG.md"):
            with gzip.GzipFile(doc / f"{name}.gz", "wb", mtime=0) as f:
                f.write((ROOT / name).read_bytes())
        (doc / "copyright").write_text(
            "Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/\n"
            f"Upstream-Name: DotMorph\nSource: https://github.com/{REPO}\n\n"
            f"Files: *\nCopyright: 2026 {MAINTAINER}\nLicense: Apache-2.0\n"
            " On Debian systems the full text is in /usr/share/common-licenses/Apache-2.0.\n"
        )
        changes = doc / "changelog.Debian.gz"
        with gzip.GzipFile(changes, "wb", mtime=0) as f:
            f.write(f"dotmorph ({ver}-1) unstable; urgency=medium\n\n"
                    f"  * New upstream release {ver}.\n\n"
                    f" -- {MAINTAINER}  {date.today():%a, %d %b %Y} 12:00:00 +0000\n".encode())
        control_dir = root / "DEBIAN"
        control_dir.mkdir()
        summary = "file converter for Linux with an animated radial menu"
        long_desc = (
            " Convert images, PDF, SVG, video, audio, Office documents and Markdown\n"
            " (440+ conversions) from a GPU-animated two-ring wheel, a screen-edge dock,\n"
            " a global hotkey, file-manager right-click menus, watch folders or the\n"
            " terminal. Uses the tools already on the system; fully local.\n"
            " .\n"
            " Part of DotSuite: https://dotsuite.dev\n"
        )
        (control_dir / "control").write_text(
            f"Package: dotmorph\nVersion: {ver}-1\nArchitecture: all\n"
            f"Maintainer: {MAINTAINER}\nInstalled-Size: {_dir_size_kb(root)}\n"
            f"Depends: {', '.join(DEB_DEPENDS)}\nRecommends: {', '.join(DEB_RECOMMENDS)}\n"
            f"Suggests: {', '.join(DEB_SUGGESTS)}\nSection: graphics\nPriority: optional\n"
            f"Homepage: {HOMEPAGE}\nDescription: {summary}\n{long_desc}"
        )
        for script, body in {
            "postinst": "#!/bin/sh\nset -e\nif command -v py3compile >/dev/null 2>&1; then\n"
                        "    py3compile -p dotmorph\nfi\n",
            "prerm": "#!/bin/sh\nset -e\nif command -v py3clean >/dev/null 2>&1; then\n"
                     "    py3clean -p dotmorph\nfi\n",
        }.items():
            (control_dir / script).write_text(body)
            (control_dir / script).chmod(0o755)
        for path in root.rglob("*"):  # predictable permissions whatever the umask
            if path.is_dir():
                path.chmod(0o755)
            elif not os.access(path, os.X_OK):
                path.chmod(0o644)
        DIST.mkdir(exist_ok=True)
        out = DIST / f"dotmorph_{ver}-1_all.deb"
        subprocess.run(["dpkg-deb", "--root-owner-group", "-Zxz", "--build", str(root), str(out)],
                       check=True, stdout=subprocess.DEVNULL)
    print(f"built {_show(out)}")
    return out


# ---- AppImage -------------------------------------------------------------------------------

# manylinux_2_28 wheels: runs on glibc 2.28+. Written with ~= (6.9.x): python-appimage passes
# requirements through the shell unquoted, so "<" or ">" would become redirections.
APPIMAGE_PYSIDE = "PySide6-Essentials~=6.9.0"


def cmd_appimage(args: argparse.Namespace) -> Path:
    ver = version()
    wheels = sorted(DIST.glob(f"dotmorph-{ver}-py3-none-any.whl"))
    if not wheels:
        raise SystemExit(f"build the wheel first: python -m build  (no dist/dotmorph-{ver}-*.whl)")
    exe = shutil.which("python-appimage")
    if not exe:
        raise SystemExit("pip install python-appimage")
    with tempfile.TemporaryDirectory() as tmp:
        recipe = Path(tmp) / "dotmorph"
        recipe.mkdir()
        # PySide6 6.10+ wheels need glibc 2.34; 6.9 needs 2.28 (Ubuntu 20.04, Debian 11,
        # RHEL 8). The whole test suite passes on 6.9, so the AppImage stays on it.
        # PySide6 first (pinned), then the wheel without the [gui] extra, so pip can't swap in
        # a newer PySide6 that needs glibc 2.34
        (recipe / "requirements.txt").write_text(f"{APPIMAGE_PYSIDE}\n{wheels[-1]}\n")
        (recipe / "entrypoint.sh").write_text(
            '#! /bin/bash\n{{ python-executable }} -I -m dotmorph "$@"\n'
        )
        desktop = (ASSETS / "dotmorph.desktop").read_text()
        (recipe / "dotmorph.desktop").write_text(desktop)
        shutil.copyfile(ASSETS / "icons/dotmorph-256.png", recipe / "dotmorph.png")
        shutil.copyfile(ASSETS / f"{APP_ID}.metainfo.xml", recipe / f"{APP_ID}.appdata.xml")
        subprocess.run([exe, "build", "app", "-l", args.linux_tag, "-p", args.python, "-n",
                        "DotMorph", str(recipe)], check=True, cwd=tmp)
        built = next(Path(tmp).glob("DotMorph-*.AppImage"))
        DIST.mkdir(exist_ok=True)
        out = DIST / f"DotMorph-{ver}-{built.stem.split('-')[-1]}.AppImage"
        shutil.move(built, out)
        out.chmod(0o755)
    print(f"built {_show(out)}")
    return out


