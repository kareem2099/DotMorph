def _roff(text: str) -> str:
    text = text.replace("\\", "\\e").replace("-", "\\-")
    return "\n".join(("\\&" + ln) if ln.startswith((".", "'")) else ln for ln in text.splitlines())


def manpage() -> str:
    from dotmorph.cli import _parser
    from dotmorph.completions import _subcommands

    parser = _parser()
    out = [
        f'.TH DOTMORPH 1 "{changelog_releases()[0][1]}" "DotMorph {version()}" "User Commands"',
        ".SH NAME",
        "dotmorph \\- convert files from a radial menu, the file manager or the terminal",
        ".SH SYNOPSIS",
        ".B dotmorph",
        "[\\fB\\-\\-theme\\fR \\fIdark|light|glass\\fR] [\\fB\\-\\-reduce\\-motion\\fR] "
        "[\\fB\\-\\-clipboard\\fR] [\\fB\\-\\-no\\-daemon\\fR] [\\fIFILE\\fR...]",
        ".br",
        ".B dotmorph",
        "\\fICOMMAND\\fR [\\fIOPTIONS\\fR]",
        ".SH DESCRIPTION",
        _roff(
            "DotMorph converts images, PDF, SVG, video, audio, Office documents and Markdown "
            "using the tools installed on the system (Pillow, librsvg, poppler, Ghostscript, "
            "ImageMagick, ffmpeg, LibreOffice, pandoc). Without a command it opens the radial "
            "menu for the given files; through the daemon this takes about 0.1 s."
        ),
        ".SH COMMANDS",
    ]
    for name, (help_text, sub) in _subcommands(parser).items():
        out += [".TP", f"\\fB{name}\\fR", _roff(help_text[:1].upper() + help_text[1:] + ".")]
        for action in sub._actions:
            if not action.option_strings or "-h" in action.option_strings:
                continue
            flags = ", ".join(f"\\fB{_roff(o)}\\fR" for o in action.option_strings)
            meta = f" \\fI{action.metavar or action.dest.upper()}\\fR" if action.nargs != 0 else ""
            out += [".RS", ".TP", flags + meta, _roff((action.help or "").replace("%%", "%")),
                    ".RE"]
    out += [
        ".SH FILES",
        ".TP", "\\fI~/.config/dotmorph/settings.json\\fR",
        "Theme, language, options, pinned and hidden formats, edge dock position.",
        ".TP", "\\fI$XDG_RUNTIME_DIR/dotmorph.sock\\fR", "The daemon's socket.",
        ".SH ENVIRONMENT",
        ".TP", "\\fBDOTMORPH_THEME\\fR", "dark, light or glass; overrides the saved theme.",
        ".TP", "\\fBDOTMORPH_REDUCE_MOTION\\fR", "1 turns the wheel's animations off.",
        ".SH EXIT STATUS",
        "0 when everything converted, 1 when something failed, 130 when cancelled.",
        ".SH EXAMPLES",
        ".nf",
        _roff("dotmorph photo.png\n"
              "dotmorph convert report.pdf --to png --dpi 200\n"
              "dotmorph convert holiday.mov --to mp4\n"
              "dotmorph convert shots/*.png --preset web\n"
              "dotmorph watch ~/Downloads --from heic --to jpg --install\n"
              "dotmorph doctor"),
        ".fi",
        ".SH SEE ALSO",
        "\\fBffmpeg\\fR(1), \\fBpdftoppm\\fR(1), \\fBgs\\fR(1), \\fBmagick\\fR(1), "
        "\\fBpandoc\\fR(1)",
        ".PP",
        _roff(HOMEPAGE),
        ".SH AUTHOR",
        "FreeRave (Kareem), part of DotSuite (https://dotsuite.dev).",
        "",
    ]
    return "\n".join(out)


def text_assets() -> dict[str, str]:
    """Generated text files, relative to packaging/linux/."""
    from dotmorph import completions
    from dotmorph.cli import _parser
    from dotmorph.linux.integrate import desktop_entry, settings_entry

    return {
        "dotmorph.desktop": desktop_entry("dotmorph", every=True),
        "dotmorph-settings.desktop": settings_entry("dotmorph"),
        f"{APP_ID}.metainfo.xml": metainfo(),
        "dotmorph.1": manpage(),
        "completions/dotmorph.bash": completions.generate("bash", _parser()),
        "completions/_dotmorph": completions.generate("zsh", _parser()),
        "completions/dotmorph.fish": completions.generate("fish", _parser()),
    }


def _show(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def cmd_assets(_: argparse.Namespace) -> None:
    from dotmorph.core.backends.svg import render

    for rel, body in text_assets().items():
        path = ASSETS / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        print(f"wrote {path.relative_to(ROOT)}")
    svg = SRC / "dotmorph" / "ui" / "icons" / "dotmorph.svg"
    icons = ASSETS / "icons"
    icons.mkdir(exist_ok=True)
    shutil.copyfile(svg, icons / "dotmorph.svg")
    for size in PNG_SIZES:
        render(svg, icons / f"dotmorph-{size}.png", scale=size / 256)
    print(f"wrote {icons.relative_to(ROOT)}/ (svg + {len(PNG_SIZES)} png sizes)")


def install_share(root: Path, zsh_dir: str = "share/zsh/site-functions") -> None:
    """Copy packaging/linux/ into <root>/usr/share the way Linux distributions expect."""
    usr = root / "usr"

    def put(src: str, dest: str, mode: int = 0o644) -> None:
        target = usr / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ASSETS / src, target)
        target.chmod(mode)

    put("dotmorph.desktop", "share/applications/dotmorph.desktop")
    put("dotmorph-settings.desktop", "share/applications/dotmorph-settings.desktop")
    put(f"{APP_ID}.metainfo.xml", f"share/metainfo/{APP_ID}.metainfo.xml")
    put("icons/dotmorph.svg", "share/icons/hicolor/scalable/apps/dotmorph.svg")
    for size in PNG_SIZES:
        put(f"icons/dotmorph-{size}.png", f"share/icons/hicolor/{size}x{size}/apps/dotmorph.png")
    put("completions/dotmorph.bash", "share/bash-completion/completions/dotmorph")
    put("completions/_dotmorph", f"{zsh_dir}/_dotmorph")
    put("completions/dotmorph.fish", "share/fish/vendor_completions.d/dotmorph.fish")
    man = usr / "share/man/man1/dotmorph.1.gz"
    man.parent.mkdir(parents=True, exist_ok=True)
    with gzip.GzipFile(man, "wb", mtime=0) as f:
        f.write((ASSETS / "dotmorph.1").read_bytes())


# ---- checks -------------------------------------------------------------------------------


def cmd_check(args: argparse.Namespace) -> None:
    from dotmorph import __version__

    ver = version()
    problems = []
    if __version__ != ver:
        problems.append(f"src/dotmorph/__init__.py says {__version__}, pyproject says {ver}")
    releases = changelog_releases()
    if not releases or releases[0][0] != ver:
        problems.append(f"CHANGELOG.md's newest section is not {ver}")
    for rel, body in text_assets().items():
        path = ASSETS / rel
        if not path.exists() or path.read_text() != body:
            problems.append(f"packaging/linux/{rel} is out of date: run packaging/build.py assets")
    if args.tag and args.tag.lstrip("v") != ver:
        problems.append(f"tag {args.tag} does not match version {ver}")
    if problems:
        raise SystemExit("\n".join(problems))
    print(f"ok: version {ver} everywhere")


def cmd_notes(args: argparse.Namespace) -> None:
    sys.stdout.write(release_notes((args.version or version()).lstrip("v")))


