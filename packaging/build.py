def version() -> str:
    """pyproject.toml's version (a regex: tomllib needs Python 3.11, we support 3.10)."""
    m = re.search(r'^version\s*=\s*"([^"]+)"', (ROOT / "pyproject.toml").read_text(), re.MULTILINE)
    if not m:
        raise SystemExit("no version in pyproject.toml")
    return m.group(1)


def changelog_releases() -> list[tuple[str, str]]:
    """[(version, date), ...] newest first, from CHANGELOG.md headings."""
    text = (ROOT / "CHANGELOG.md").read_text()
    return re.findall(r"^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})", text, re.MULTILINE)


def release_notes(ver: str) -> str:
    text = (ROOT / "CHANGELOG.md").read_text()
    m = re.search(rf"^## \[{re.escape(ver)}\].*?$(.*?)(?=^## \[|^\[\d|\Z)", text,
                  re.MULTILINE | re.DOTALL)
    if not m:
        raise SystemExit(f"no CHANGELOG section for {ver}")
    body = m.group(1).strip().strip("-").strip()
    return body + f"\n\n**Full changelog:** https://github.com/{REPO}/blob/v{ver}/CHANGELOG.md\n"


