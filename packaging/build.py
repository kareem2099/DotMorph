def tarball_url(ver: str) -> str:
    return f"https://github.com/{REPO}/archive/refs/tags/v{ver}.tar.gz"


def pkgbuild(ver: str, sha256: str) -> str:
    def arr(items: list[str]) -> str:
        return "\n".join(f"  '{i}'" for i in items)

    return f"""# Maintainer: {MAINTAINER}
# Generated by packaging/build.py aur
pkgname=dotmorph
pkgver={ver}
pkgrel=1
pkgdesc="File converter for Linux with an animated radial menu: 440+ conversions"
arch=('any')
url="{HOMEPAGE}"
license=('Apache-2.0')
depends=(
{arr(AUR_DEPENDS)}
)
optdepends=(
{arr(AUR_OPTDEPENDS)}
)
makedepends=('python-build' 'python-installer' 'python-hatchling')
source=("$pkgname-$pkgver.tar.gz::{tarball_url('$pkgver')}")
sha256sums=('{sha256}')

build() {{
  cd "DotMorph-$pkgver"
  python -m build --wheel --no-isolation
}}

package() {{
  cd "DotMorph-$pkgver"
  python -m installer --destdir="$pkgdir" dist/*.whl
  python packaging/build.py install-share --root "$pkgdir"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}}
"""


def srcinfo(ver: str, sha256: str) -> str:
    lines = [
        "pkgbase = dotmorph",
        "\tpkgdesc = File converter for Linux with an animated radial menu: 440+ conversions",
        f"\tpkgver = {ver}",
        "\tpkgrel = 1",
        f"\turl = {HOMEPAGE}",
        "\tarch = any",
        "\tlicense = Apache-2.0",
        *(f"\tmakedepends = {d}" for d in ("python-build", "python-installer",
                                           "python-hatchling")),
        *(f"\tdepends = {d}" for d in AUR_DEPENDS),
        *(f"\toptdepends = {d}" for d in AUR_OPTDEPENDS),
        f"\tsource = dotmorph-{ver}.tar.gz::{tarball_url(ver)}",
        f"\tsha256sums = {sha256}",
        "",
        "pkgname = dotmorph",
        "",
    ]
    return "\n".join(lines)


def cmd_aur(args: argparse.Namespace) -> Path:
    ver = version()
    sha = "SKIP"
    if args.tarball:
        sha = hashlib.sha256(Path(args.tarball).read_bytes()).hexdigest()
    elif args.fetch:
        with urllib.request.urlopen(tarball_url(ver), timeout=60) as resp:  # noqa: S310
            sha = hashlib.sha256(resp.read()).hexdigest()
    out = DIST / "aur"
    out.mkdir(parents=True, exist_ok=True)
    (out / "PKGBUILD").write_text(pkgbuild(ver, sha))
    (out / ".SRCINFO").write_text(srcinfo(ver, sha))
    print(f"wrote {_show(out)}/PKGBUILD and .SRCINFO (sha256 {sha[:12]})")
    return out


def cmd_install_share(args: argparse.Namespace) -> None:
    install_share(Path(args.root))


def cmd_sdist_check(_: argparse.Namespace) -> None:
    """The sdist must contain what the AUR build and the man page need."""
    ver = version()
    sdist = DIST / f"dotmorph-{ver}.tar.gz"
    with tarfile.open(sdist) as tar:
        names = {n.split("/", 1)[1] for n in tar.getnames() if "/" in n}
    need = {"packaging/build.py", "packaging/linux/dotmorph.desktop", "LICENSE", "CHANGELOG.md",
            "src/dotmorph/ui/qml/main.qml", "src/dotmorph/ui/icons/dotmorph.svg"}
    missing = sorted(need - names)
    if missing:
        raise SystemExit(f"sdist is missing: {missing}")
    print(f"ok: {sdist.name} has packaging files")


# ---- checksums and signatures ---------------------------------------------------------------

SUMS = "SHA256SUMS"
PUBKEY = "dotmorph-signing-key.asc"


def release_files(folder: Path) -> list[Path]:
    """Files that get a checksum and a signature (not the signatures themselves)."""
    skip = {SUMS, PUBKEY, "RELEASE_NOTES.md"}
    return sorted(p for p in folder.iterdir()
                  if p.is_file() and p.suffix != ".asc" and p.name not in skip)


def write_sums(folder: Path) -> Path:
    lines = [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}"
             for p in release_files(folder)]
    out = folder / SUMS
    out.write_text("\n".join(lines) + "\n")
    return out


def sign(folder: Path, key: str | None = None) -> list[Path]:
    """Detached ASCII-armored signature (file.asc) for every release file and SHA256SUMS,
    plus the public key so users can verify. `key`: GPG key id or fingerprint."""
    gpg = shutil.which("gpg")
    if not gpg:
        raise SystemExit("gpg not found")
    base = [gpg, "--batch", "--yes", "--pinentry-mode", "loopback"]
    if os.environ.get("GPG_PASSPHRASE"):
        base += ["--passphrase-fd", "0"]
    if key:
        base += ["--local-user", key]
    signed = []
    for path in [*release_files(folder), folder / SUMS]:
        asc = path.with_name(path.name + ".asc")
        subprocess.run([*base, "--armor", "--detach-sign", "--output", str(asc), str(path)],
                       input=os.environ.get("GPG_PASSPHRASE", "").encode(), check=True)
        signed.append(asc)
    export = [gpg, "--batch", "--armor", "--export"] + ([key] if key else [])
    (folder / PUBKEY).write_bytes(subprocess.run(export, capture_output=True,
                                                 check=True).stdout)
    return signed


def cmd_sums(args: argparse.Namespace) -> None:
    folder = Path(args.folder)
    out = write_sums(folder)
    print(f"wrote {_show(out)} ({len(release_files(folder))} files)")
    if args.sign:
        signed = sign(folder, args.key)
        print(f"signed {len(signed)} files, public key in {PUBKEY}")


